"""Making the SDK of a project: the files of a Python package, in memory.

The package has each shipped module as the project wrote it (so `from demo_app.models import
Person` works on a client as on the server), a type stub for each that declares models, a
manifest, and a small module named after the project with `connect()`.
"""

import dataclasses
import hashlib
import importlib.metadata
import json
import re
import sys
from pathlib import Path
from typing import Any

from pangloss_models.migrations.files import graph_of
from pangloss_models.typestubs import (
    modules_with_models,
    registered_class_names,
    stub_for_module,
)

from pangloss_sdk_server import config
from pangloss_sdk_server.closure import Closure, closure_of, locate

# Distributions the SDK has already (through `pangloss-sdk`), or that name Pangloss itself
ALREADY_THERE = {"annotated-types", "pydantic", "pydantic-core", "frozendict", "pydantic-settings"}


class SdkBuildError(Exception):
    """The SDK cannot be built; the message says why (and `problems` lists what)"""

    def __init__(self, message: str, problems: list[str] | None = None):
        super().__init__(message)
        self.problems = problems or []


@dataclasses.dataclass
class Package:
    """The files of an SDK: path (relative to the package root, with `/`) -> content"""

    files: dict[str, bytes]
    manifest: dict[str, Any]

    @property
    def fingerprint(self) -> str:
        return self.manifest["fingerprint"]


def normalise(name: str) -> str:
    return re.sub(r"[-_.]+", "-", name).lower()


def names_for(project_name: str, settings: Any = None) -> tuple[str, str]:
    """The distribution name (`pangloss-demo-sdk`) and the import name (`pangloss_demo_sdk`)"""
    distribution = normalise(config.setting("SDK_NAME", f"{project_name}-sdk", settings))
    return distribution, distribution.replace("-", "_")


def apps_to_ship(root: Path, installed: list[str], settings: Any = None) -> list[str]:
    """The installed apps that have a `models` module in the project, less those left out.
    Framework packages (`pangloss_*`) are dependencies, not the project's"""
    only = config.setting("SDK_APPS", None, settings)
    excluded = set(config.setting("SDK_EXCLUDE_APPS", [], settings))
    return [
        app
        for app in installed
        if not app.startswith("pangloss_")
        and app not in excluded
        and (only is None or app in only)
        and locate(root, f"{app}.models") is not None
    ]


def schema_position(apps: list[str]) -> dict[str, str]:
    """The last migration of each app, as `{app: name}`: where the models are"""
    try:
        graph = graph_of(apps)
    except Exception:
        return {}
    latest: dict[str, Any] = {}
    for migration in graph.migrations.values():
        if migration.app not in latest or migration.number > latest[migration.app].number:
            latest[migration.app] = migration
    return {app: migration.name for app, migration in sorted(latest.items())}


def requirements_for(closure: Closure, settings: Any = None) -> list[str]:
    """The distributions that the shipped modules import (found from the installed
    packages), as requirements, and `SDK_EXTRA_REQUIREMENTS`"""
    owners = importlib.metadata.packages_distributions()
    required: set[str] = set()
    problems: list[str] = []
    for top in sorted(closure.outside):
        if top.startswith("pangloss"):
            continue
        distributions = owners.get(top)
        if not distributions:
            problems.append(
                f"Cannot tell which package provides `{top}` (imported by the models): add it to "
                "SDK_EXTRA_REQUIREMENTS, or remove the import"
            )
            continue
        required.update(normalise(d) for d in distributions)
    if problems:
        raise SdkBuildError("A dependency of the models is not known", problems)
    required -= ALREADY_THERE
    required.update(config.setting("SDK_EXTRA_REQUIREMENTS", [], settings))
    return sorted(required)


def sdk_requirement(settings: Any = None) -> str:
    default = f"pangloss-sdk=={importlib.metadata.version('pangloss-sdk')}"
    return config.setting("SDK_REQUIREMENT", default, settings)


def client_module_source(distribution: str, project: str) -> str:
    return f'''"""The SDK of {project}: its models, to use against its API.

Generated by `pangloss sdk build`: do not edit.

    import {distribution.replace("-", "_")} as sdk
    await sdk.connect("https://...")
    from {{app}}.models import ...
"""

import json
from pathlib import Path
from typing import Any

import pangloss_sdk

MANIFEST: dict[str, Any] = json.loads(
    (Path(__file__).parent / "manifest.json").read_text()
)
APPS: list[str] = MANIFEST["apps"]

disconnect = pangloss_sdk.disconnect
disconnect_sync = pangloss_sdk.disconnect_sync


check = pangloss_sdk.check
check_sync = pangloss_sdk.check_sync


def connect(url: str | None = None, **options: Any) -> None:
    """Connect to the server (see `pangloss_sdk.connect`): initialises the models. The
    server is told which SDK this is, and says if it is out of date"""
    pangloss_sdk.connect(url, apps=APPS, sdk=MANIFEST, **options)


def connect_offline() -> None:
    """Initialise the models with no server (to check them)"""
    pangloss_sdk.connect_offline(APPS)
'''


def pyproject_source(
    distribution: str, module: str, version: str, requires: list[str], top_levels: list[str]
) -> str:
    dependencies = ",\n".join(f'    "{r}"' for r in requires)
    packages = ", ".join(f'"{p}"' for p in sorted({module, *top_levels}))
    # (the Python the models were built and checked with: they use syntax of the newest)
    python = f"{sys.version_info.major}.{sys.version_info.minor}"
    return f"""# Generated by `pangloss sdk build`: do not edit
[project]
name = "{distribution}"
version = "{version}"
description = "The SDK of a Pangloss project: its models, to use against its API"
requires-python = ">={python}"
dependencies = [
{dependencies}
]

[build-system]
requires = ["hatchling"]
build-backend = "hatchling.build"

[tool.hatch.build.targets.wheel]
packages = [{packages}]
"""


def readme_source(distribution: str, module: str, project: str, fingerprint: str) -> str:
    return f"""# {distribution}

The SDK of **{project}**: its model classes, with type stubs, for use against its API.
Generated by `pangloss sdk build` (fingerprint `{fingerprint[:12]}`).

```python
import {module} as sdk

await sdk.connect("https://...")   # or set PANGLOSS_URL
```

Model functions (`Person.get`, `Person.Create(...).save()`, ...) are requests to the API.
A login is asked for at the first request that needs one.
"""


def content_fingerprint(files: dict[str, bytes], extra: dict[str, Any]) -> str:
    digest = hashlib.sha256()
    for path in sorted(files):
        digest.update(path.encode() + b"\0" + files[path] + b"\0")
    digest.update(json.dumps(extra, sort_keys=True).encode())
    return digest.hexdigest()


def build_package(
    root: Path,
    settings: Any,
    build_number: int = 1,
) -> Package:
    """The SDK of the project, from its settings and the models as initialised.

    `build_number` is the version of the package (`0.<n>`): the caller counts builds that
    changed something."""
    root = root.resolve()
    project = settings.PROJECT_NAME
    apps = apps_to_ship(root, list(settings.INSTALLED_APPS), settings)
    if not apps:
        raise SdkBuildError(
            "There is nothing to ship: no installed app of the project has a models module"
        )
    closure = closure_of(root, [f"{app}.models" for app in apps])
    if closure.problems:
        raise SdkBuildError("The models cannot be shipped as they are", closure.problems)
    requires = [sdk_requirement(settings), *requirements_for(closure, settings)]
    distribution, module = names_for(project, settings)

    files: dict[str, bytes] = {}
    for name, path in closure.modules.items():
        files[path.resolve().relative_to(root).as_posix()] = path.read_bytes()

    names = registered_class_names()
    for module_name, models in modules_with_models(root).items():
        if module_name not in closure.modules:
            continue
        import importlib

        imported = importlib.import_module(module_name)
        path = closure.modules[module_name].resolve().relative_to(root)
        files[path.with_suffix(".pyi").as_posix()] = stub_for_module(
            imported, models, names
        ).encode()

    tops = sorted({name.split(".")[0] for name in closure.modules})
    for top in tops:
        files[f"{top}/py.typed"] = b""
    files[f"{module}/__init__.py"] = client_module_source(distribution, project).encode()
    files[f"{module}/py.typed"] = b""

    position = schema_position(list(settings.INSTALLED_APPS))
    fingerprint = content_fingerprint(
        files, {"requires": requires, "apps": apps, "name": distribution}
    )
    version = f"0.{build_number}"
    manifest = {
        "project": project,
        "distribution": distribution,
        "module": module,
        "version": version,
        "apps": apps,
        "modules": sorted(closure.modules),
        "requires": requires,
        "fingerprint": fingerprint,
        "schema_position": position,
        "pangloss_sdk_version": importlib.metadata.version("pangloss-sdk"),
    }
    files[f"{module}/manifest.json"] = (json.dumps(manifest, indent=2, sort_keys=True) + "\n").encode()
    files["pyproject.toml"] = pyproject_source(
        distribution, module, version, requires, tops
    ).encode()
    files["README.md"] = readme_source(distribution, module, project, fingerprint).encode()
    return Package(files, manifest)
