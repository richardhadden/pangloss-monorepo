# The stub of a module
# ---------------------------------------------------------------------------

ELLIPSIS = ast.Expr(ast.Constant(Ellipsis))
TYPE_DEFINITIONS = {"TypeVar", "ParamSpec", "TypeVarTuple", "NewType", "TypeAliasType"}


def name_of(node: ast.expr) -> str | None:
    if isinstance(node, ast.Name):
        return node.id
    if isinstance(node, ast.Attribute):
        return node.attr
    return None


def is_kept_value(node: ast.expr | None, definitions: bool = False) -> bool:
    """Whether the value of an assignment is kept in a stub (rather than `...`):
    constants (such as the members of an enum), a `Field(...)` (which says whether a
    field has a default), and the definition of a type"""
    if isinstance(node, ast.Constant):
        return True
    if isinstance(node, ast.Call):
        name = name_of(node.func)
        return name == "Field" or (definitions and name in TYPE_DEFINITIONS)
    if definitions:
        return isinstance(node, (ast.Name, ast.Attribute, ast.Subscript)) or (
            isinstance(node, ast.BinOp) and isinstance(node.op, ast.BitOr)
        )
    return False


class Stubifier:
    """Makes the stub of a module from its source: the same declarations, without
    function bodies, and with nested classes added to the models"""

    def __init__(self, renderer: TypeRenderer, models: dict[str, type]) -> None:
        self.renderer = renderer
        # The models of the module, by qualified name
        self.models = models
        # The source to put in place of a placeholder statement (`ast.unparse` does
        # not keep comments, so the nested classes are put in as text afterwards)
        self.insertions: dict[str, str] = {}

    def module(self, tree: ast.Module) -> ast.Module:
        return ast.Module(body=self.body(tree.body, ""), type_ignores=[])

    def body(self, statements: Iterable[ast.stmt], prefix: str) -> list[ast.stmt]:
        result: list[ast.stmt] = []
        in_class = bool(prefix)
        for statement in statements:
            result.extend(self.statement(statement, prefix, in_class))
        return result

    def statement(
        self, node: ast.stmt, prefix: str, in_class: bool
    ) -> list[ast.stmt]:
        match node:
            case ast.Import() | ast.ImportFrom():
                # (a lazy import is imported as usual in a stub)
                if getattr(node, "is_lazy", 0):
                    setattr(node, "is_lazy", 0)
                return [node]
            case ast.ClassDef():
                return [self.class_definition(node, prefix)]
            case ast.FunctionDef() | ast.AsyncFunctionDef():
                node.body = [ELLIPSIS]
                return [node]
            case ast.AnnAssign():
                if not is_kept_value(node.value):
                    node.value = ast.Constant(Ellipsis) if node.value else None
                return [node]
            case ast.Assign():
                if not all(isinstance(t, ast.Name) for t in node.targets):
                    return []
                if not is_kept_value(node.value, definitions=not in_class):
                    node.value = ast.Constant(Ellipsis)
                return [node]
            case ast.If():
                node.body = self.body_or_pass(node.body, prefix)
                node.orelse = self.body(node.orelse, prefix)
                return [node]
            case ast.Try():
                # (the alternatives of an import, each as they are)
                return [
                    *self.body(node.body, prefix),
                    *(s for h in node.handlers for s in self.body(h.body, prefix)),
                    *self.body(node.orelse, prefix),
                ]
            case _:
                if type(node).__name__ == "TypeAlias":
                    return [node]
                return []

    def body_or_pass(self, statements: list[ast.stmt], prefix: str) -> list[ast.stmt]:
        return self.body(statements, prefix) or [ELLIPSIS]

    def class_definition(self, node: ast.ClassDef, prefix: str) -> ast.ClassDef:
        qualified_name = f"{prefix}{node.name}"
        body = self.body(node.body, f"{qualified_name}.")
        if model := self.models.get(qualified_name):
            if source := nested_classes_of(self.renderer, model):
                placeholder = f"__nested_classes_of_{len(self.insertions)}__"
                self.insertions[placeholder] = source
                body.append(ast.Expr(ast.Name(placeholder)))
        node.body = body or [ELLIPSIS]
        return node


def stub_for_module(
    module: types.ModuleType,
    models: Iterable[type],
    names: dict[type, tuple[str, str]] | None = None,
) -> str:
    """The source of the stub of a module, for the models (initialised) in it"""
    path = module_source_path(module)
    tree = ast.parse(path.read_text())

    renderer = TypeRenderer(module.__name__, names)
    stubifier = Stubifier(renderer, {m.__qualname__: m for m in models})
    stub = stubifier.module(tree)
    code = ast.unparse(ast.fix_missing_locations(stub))
    for placeholder, source in stubifier.insertions.items():
        code = insert_source(code, placeholder, source)

    imports = "\n".join(renderer.import_lines())
    return "\n".join([GENERATED_HEADER, *CHECKER_COMMENTS, imports, "", code, ""])


def insert_source(code: str, placeholder: str, source: str) -> str:
    """Put source in place of a line that is only the placeholder, at its indentation"""
    lines = code.split("\n")
    for index, line in enumerate(lines):
        if line.strip() == placeholder:
            indent = line[: len(line) - len(line.lstrip())]
            inserted = [f"{indent}{l}" if l else l for l in source.split("\n")]
            return "\n".join([*lines[:index], *inserted, *lines[index + 1 :]])
    raise ValueError(f"No place for {placeholder}")


def module_source_path(module: types.ModuleType) -> Path:
    file = getattr(module, "__file__", None)
    if not file or not file.endswith(".py"):
        raise ValueError(f"{module.__name__} has no Python source file")
    return Path(file)


def stub_path(module: types.ModuleType) -> Path:
    return module_source_path(module).with_suffix(".pyi")


