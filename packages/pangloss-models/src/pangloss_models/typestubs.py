Operations = typing.Literal["async", "sync"]

# (aliases, so that they cannot be the name of something in the module)
OPERATION_IMPORTS = (
    "import builtins as _pg_builtins",
    "import typing as _pg_typing",
    "import uuid as _pg_uuid",
    "import pydantic as _pg_pydantic",
    "from pangloss_models.model_bases.base_models import _ListItems as _PgListItems",
    "from pangloss_models.search import Match as _PgMatch",
)


def has_operations(model: type) -> bool:
    """Whether the model has `get`, `list`, `save` and the like: a Document or Entity that is
    not abstract"""
    from pangloss_models.model_bases.document import Document
    from pangloss_models.model_bases.entity import Entity

    return (
        issubclass(model, (Document, Entity))
        and not getattr(model._meta, "abstract", False)
        and hasattr(model, "HeadView")
    )


def save_methods(
    model_name: str, name: str, mode: Operations, is_document: bool = False
) -> list[str]:
    """`save` of a `Create` or `Update`: the reference view, or with `detail=True` the head view"""
    define = "async def" if mode == "async" else "def"
    more = ", expected_version: int | None = None" if name == "Update" else ""
    if is_document:
        # (with `pangloss-review`; without it, they are ignored)
        more += ", published: bool | None = None, review_status: str | None = None"
    reference, head = f"{model_name}.ReferenceView", f"{model_name}.HeadView"
    return [
        "@_pg_typing.overload  # type: ignore",
        f"{define} save(self, detail: _pg_typing.Literal[False] = False{more}) -> {reference}: ...  # type: ignore",
        "@_pg_typing.overload  # type: ignore",
        f"{define} save(self, detail: _pg_typing.Literal[True]{more}) -> {head}: ...  # type: ignore",
    ]


def operations_source(model: type, qualified_name: str, mode: Operations) -> str:
    """The functions bound to a model by the database module, as the stub of a class body:
    `async` or blocking according to the database module they are for"""
    from pangloss_models.model_bases.entity import Entity

    define = "async def" if mode == "async" else "def"
    is_entity = issubclass(model, Entity)
    id_type = (
        "_pg_uuid.UUID | _pg_pydantic.AnyHttpUrl" if is_entity else "_pg_uuid.UUID"
    )
    head = f"{qualified_name}.HeadView"
    # (what a search of it can be ordered by, as names: `order_by=["title"]`)
    order_fields = (
        "_pg_typing.Literal["
        + ", ".join(repr(name) for name in orderable_fields(model))
        + "]"
    )
    lines = [
        "@classmethod",
        f"{define} get(cls, id: {id_type}) -> {head} | None: ...  # type: ignore",
    ]
    if is_entity:
        lines += [
            "@classmethod",
            f"{define} get_for_edit(cls, id: {id_type}) -> {qualified_name}.EditView | None: ...  # type: ignore",
        ]
    lines += [
        "@classmethod",
        f"{define} list(cls, search_terms: str | None = None, page_number: int | None = None, "
        f"page_size: int | None = None, deep_search: bool = False, "
        f"published: bool | None = None, review_status: str | None = None) "
        f"-> _PgListItems[{qualified_name}.ReferenceView]: ...  # type: ignore",
        "@classmethod",
        f"{define} search(cls, pattern: {qualified_name}.Where | _PgMatch | None = None, "
        f"page_number: int | None = None, page_size: int | None = None, *, "
        f"order_by: _pg_builtins.list[{qualified_name}.Order | {order_fields}] | None = None) "
        f"-> _PgListItems[{qualified_name}.ReferenceView]: ...  # type: ignore",
        "@classmethod",
        f"{define} delete(cls, id: {id_type}) -> None: ...  # type: ignore",
        "@classmethod",
        f"{define} undelete(cls, id: {id_type}) -> None: ...  # type: ignore",
    ]
    return "\n".join(lines)


def stub_annotation(field: typing.Any) -> typing.Any:
    """The annotation of a field as a type checker is to see it: a `StubAnnotation` of its metadata, if it has one (a
    `Where` field takes any `Var` when validated, and a `Var` of what it holds in the stubs)"""
    from pangloss_models.search_where import StubAnnotation

    for item in field.metadata:
        if isinstance(item, StubAnnotation):
            return item.annotation
    return field.annotation


def keyword_init(cls: type) -> bool:
    """Whether the stub of a class has its `__init__` written out: a search pattern (`Person.Where`), and a class that
    asks for it (`_stub_init`, as the head of a rule of `pangloss-derived` does). A type checker is lenient with the
    arguments of a pydantic class whose fields can be of a class that is not a model (a `Var`): it takes any value. With
    an `__init__`, it checks each argument as it checks a call of a function"""
    from pangloss_models.search_where import Where

    return issubclass(cls, Where) or bool(getattr(cls, "_stub_init", False))


def init_source(renderer: TypeRenderer, cls: type[BaseModel]) -> str:
    """`def __init__(self, *, a: ..., b: ... = ...) -> None: ...`, of the fields of the class by their Python names"""
    parameters = [
        f"{field_name}: {renderer.render(stub_annotation(field))}"
        + ("" if field.is_required() else " = ...")
        for field_name, field in cls.model_fields.items()
    ]
    # (those without a default first, as Python wants)
    parameters.sort(key=lambda p: p.endswith(" = ..."))
    joined = ", ".join(["self", "*", *parameters]) if parameters else "self"
    return f"def __init__({joined}) -> None: ...  # type: ignore"


def stub_nested_class(
    renderer: TypeRenderer,
    name: str,
    cls: type[BaseModel],
    operations: Operations | None = None,
    model_name: str = "",
    is_document: bool = False,
    create_directly: bool = True,
) -> str:
    # (the class overrides the one of the base class of the model, which a type checker
    # takes for a mistake)
    bases = ", ".join(renderer.base_names(cls))
    lines = [f"class {name}({bases}):  # type: ignore"]
    for field_name, field in cls.model_fields.items():
        annotation = renderer.render(stub_annotation(field))
        default = "" if field.is_required() else " = ..."

        # A field the class has from a base class is left out, unless it is changed
        inherited = [
            base.model_fields[field_name]
            for base in cls.__bases__
            if isinstance(base, type)
            and issubclass(base, BaseModel)
            and field_name in base.model_fields
        ]
        same = [
            f
            for f in inherited
            if renderer.render(stub_annotation(f)) == annotation
            and f.is_required() == field.is_required()
        ]
        if same:
            continue
        ignore = "  # type: ignore" if inherited else ""
        lines.append(f"    {field_name}: {annotation}{default}{ignore}")
    # (no `save` of the `Create` of a document that cannot be made on its own: `create_directly`)
    if operations and (name == "Update" or (name == "Create" and create_directly)):
        lines += [
            f"    {line}"
            for line in save_methods(model_name, name, operations, is_document)
        ]
    if keyword_init(cls):
        lines.append(f"    {init_source(renderer, cls)}")
    if len(lines) == 1:
        lines.append("    ...")
    return "\n".join(lines)


def nested_classes_of(
    renderer: TypeRenderer,
    model: type,
    operations: Operations | None = None,
    qualified_name: str = "",
    refer_as: str | None = None,
) -> str:
    """The source of the nested classes to add to a model (with the `save` of `Create` and
    `Update`, and the model's own `get`, `list` and so on, if `operations` says which kind).
    `refer_as`: the name the model's own functions call it by, if not its own (`own_name_is_taken`)"""
    from pangloss_models.model_bases.document import Document

    operations = operations if operations and has_operations(model) else None
    parts = [
        stub_nested_class(
            renderer,
            name,
            cls,
            operations,
            qualified_name,
            issubclass(model, Document),
            getattr(getattr(model, "_meta", None), "create_directly", True),
        )
        for name, cls in generated_classes(model).items()
        if is_for_users(name)
    ]
    if operations:
        parts.append(operations_source(model, refer_as or qualified_name, operations))
    return "\n\n".join(parts)


def own_name_is_taken(model: type) -> bool:
    """Whether a class made for the model has the model's name (a model called `Order` has `Order.Order`, what its
    searches are ordered by): in the body of the model's class the name is then that class, not the model, and the
    types of `get`, `list` and `search`, which are written there, would be of the wrong one"""
    return model.__name__ in generated_classes(model)


