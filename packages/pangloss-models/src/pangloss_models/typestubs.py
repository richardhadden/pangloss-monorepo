"""Type stubs (`.pyi` files) for the modules that declare models.

The classes made for each model when the models are initialised (`Person.Create`,
`Person.HeadView` and so on) are made at runtime, so a type checker or an editor cannot
see them. `stub_for_module` writes the source of a stub for a module, in which each
model has those classes as nested classes, with their fields, so that they can be
completed.

A stub replaces its module for a type checker, so it has the whole of the module in
it: everything the module declares is kept (without function bodies or values), and
the nested classes are added to the models.
"""

import ast
import enum
import importlib
import sys
import types
import typing
from collections.abc import Iterable
from pathlib import Path

from pydantic import BaseModel

from pangloss_models.model_registry import ModelRegistry

GENERATED_HEADER = "# Generated by `pangloss make-stubs`: do not edit"
# (a type checker would find these in a stub, as the nested class `Create` of a model
# is not the `ClassVar` of its base class)
CHECKER_COMMENTS = (
    "# pyright: basic, reportIncompatibleVariableOverride=false, "
    "reportIncompatibleMethodOverride=false",
    "# mypy: ignore-errors",
)

# The generated classes that are not for a user of the models
INTERNAL_CLASS_NAMES = {"Meta"}


def is_generated(text: str) -> bool:
    return text.startswith(GENERATED_HEADER)


# ---------------------------------------------------------------------------
# Naming classes
# ---------------------------------------------------------------------------


def generated_classes(model: type) -> dict[str, type[BaseModel]]:
    """The classes that initialising a model made for it, by name (`Create`, ...)"""
    return {
        name: value
        for name, value in vars(model).items()
        if isinstance(value, type)
        and issubclass(value, BaseModel)
        and name not in INTERNAL_CLASS_NAMES
        and not name.startswith("_")
    }


def is_for_users(name: str) -> bool:
    """(the `CreateDB` and `UpdateDB` models are for the database)"""
    return not name.endswith("DB")


def importable(module_name: str, qualified_name: str, cls: type) -> bool:
    """Whether the class is found where it says it is"""
    found: typing.Any = sys.modules.get(module_name)
    for part in qualified_name.split("."):
        found = getattr(found, part, None)
        if found is None:
            return False
    return found is cls


class TypeRenderer:
    """Writes types as the source of annotations in the stub of one module, noting
    the imports needed"""

    def __init__(
        self, module_name: str, names: dict[type, tuple[str, str]] | None = None
    ) -> None:
        self.module_name = module_name
        # Where classes made at runtime can be found: (module, qualified name)
        self.names = names if names is not None else registered_class_names()
        self.imports: set[str] = {"typing"}

    def class_name(self, cls: type) -> str | None:
        """How to refer to a class, or None if it cannot be referred to"""
        if cls is type(None):
            return "None"
        if cls.__module__ == "builtins":
            return cls.__qualname__
        module_name, qualified_name = self.names.get(
            cls, (cls.__module__, cls.__qualname__)
        )
        if not importable(module_name, qualified_name, cls) and cls not in self.names:
            return None
        if module_name == self.module_name:
            return qualified_name
        self.imports.add(module_name)
        return f"{module_name}.{qualified_name}"

    def render(self, annotation: typing.Any) -> str:
        """The source of an annotation; `typing.Any` for what cannot be written"""
        try:
            return self._render(annotation)
        except _Unwritable:
            return "typing.Any"

    def _render(self, annotation: typing.Any) -> str:
        if annotation is None or annotation is type(None):
            return "None"
        if annotation is typing.Any or isinstance(annotation, typing.TypeVar):
            return "typing.Any"
        if annotation is Ellipsis:
            return "..."

        origin = typing.get_origin(annotation)
        args = typing.get_args(annotation)

        if origin is typing.Annotated:
            return self._render(args[0])
        if origin is typing.Literal:
            return "typing.Literal[" + ", ".join(self._literal(a) for a in args) + "]"
        if origin is typing.Union or origin is types.UnionType:
            return " | ".join(self._render(a) for a in args)
        if origin is not None:
            if not isinstance(origin, type):
                raise _Unwritable
            name = self.class_name(origin)
            if name is None:
                raise _Unwritable
            if not args:
                return name
            # (a list of arguments, as of a `Callable`, cannot be written here)
            if any(isinstance(a, (list, tuple)) for a in args):
                return "typing.Any"
            return f"{name}[{', '.join(self._render(a) for a in args)}]"
        if isinstance(annotation, type):
            name = self.class_name(annotation)
            if name is None:
                raise _Unwritable
            return name
        raise _Unwritable

    def _literal(self, value: typing.Any) -> str:
        if isinstance(value, enum.Enum):
            name = self.class_name(type(value))
            if name is None:
                raise _Unwritable
            return f"{name}.{value.name}"
        return repr(value)

    def base_names(self, cls: type) -> list[str]:
        """The classes `cls` is a subclass of, as can be written in a stub: any that
        cannot be (a class made for a generic) is replaced by its own ancestors"""
        names: list[str] = []
        pending = list(cls.__bases__)
        while pending:
            base = pending.pop(0)
            if base is object:
                continue
            name = self.class_name(base)
            if name is None:
                pending = list(base.__bases__) + pending
            elif name not in names:
                names.append(name)
        if not names:
            self.imports.add("pydantic")
            return ["pydantic.BaseModel"]
        return names

    def import_lines(self) -> list[str]:
        return [f"import {name}" for name in sorted(self.imports)]


class _Unwritable(Exception):
    pass


def registered_class_names() -> dict[type, tuple[str, str]]:
    """Where the classes made for the registered models are: `Person.Create` is
    `Create` in `Person`, though its own module and name say otherwise"""
    names: dict[type, tuple[str, str]] = {}
    for model in ModelRegistry._models:
        if "<locals>" in model.__qualname__:
            continue
        names[model] = (model.__module__, model.__qualname__)
        for name, cls in generated_classes(model).items():
            names[cls] = (model.__module__, f"{model.__qualname__}.{name}")
    return names


