def is_in_environment(root: Path, path: Path) -> bool:
    """Whether a file is part of an installed package or a virtual environment (under
    `root`), where no stub should be written"""
    return any(
        directory.name in ("site-packages", "dist-packages")
        or (directory / "pyvenv.cfg").exists()
        for directory in path.parents
        if directory.is_relative_to(root)
    )


# Functions an optional package adds, each giving classes of its own that have classes made for them at runtime, as
# models do, and so are stubbed as models are (`pangloss-derived`: its `Derived` classes, with `Derive`, `View` and
# `Where`). Not cleared by `ModelRegistry._reset`.
stub_classes: list[typing.Callable[[], Iterable[type]]] = []


def modules_with_models(root: Path) -> dict[str, list[type]]:
    """The modules under `root` that declare registered models (or classes of `stub_classes`), with the models of each.
    (Models made inside a function cannot be named, and are left out.)"""
    root = root.resolve()
    modules: dict[str, list[type]] = {}
    extra = [cls for provider in stub_classes for cls in provider()]
    for model in [*ModelRegistry._models, *extra]:
        if "<locals>" in model.__qualname__:
            continue
        module = sys.modules.get(model.__module__)
        file = getattr(module, "__file__", None)
        if not file or not file.endswith(".py"):
            continue
        path = Path(file).resolve()
        if not path.is_relative_to(root) or is_in_environment(root, path):
            continue
        modules.setdefault(model.__module__, []).append(model)
    return modules


def write_stubs(root: Path, force: bool = False) -> tuple[list[Path], list[Path]]:
    """Write the stub of each module under `root` that declares models, (writing
    over a stub that was not generated only if `force`). Returns the paths written, and
    those left alone because there is a stub that was not generated."""
    names = registered_class_names()
    written: list[Path] = []
    skipped: list[Path] = []
    for module_name, models in sorted(modules_with_models(root).items()):
        module = importlib.import_module(module_name)
        path = stub_path(module)
        if path.exists() and not force and not is_generated(path.read_text()):
            skipped.append(path)
            continue
        path.write_text(stub_for_module(module, models, names))
        written.append(path)
    return written, skipped
