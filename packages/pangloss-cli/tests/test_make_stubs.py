import ast
from pathlib import Path

import pytest
from pangloss_cli.main import build_app
from pangloss_models.model_registry import ModelRegistry
from typer.testing import CliRunner

from cli_support import write

runner = CliRunner()

MODELS = """
    import enum
    from typing import Annotated

    from pangloss_models.model_bases.document import Document
    from pangloss_models.model_bases.entity import Entity


    class Colour(enum.Enum):
        RED = "red"


    class Place(Entity):
        name: str | None = None

        def shout(self) -> str:
            return self.label.upper()


    class Person(Entity):
        born_in: Place
        colour: Colour


    class Statement(Document):
        about: Person
"""


@pytest.fixture(autouse=True)
def clean_registry():
    ModelRegistry._reset()
    yield
    ModelRegistry._reset()


def make_stubs(*args: str):
    app = build_app(argv=[], environment={})
    result = runner.invoke(app, ["make-stubs", *args])
    return result.exit_code, result.output + result.stderr


def nested(tree: ast.Module, model: str) -> dict[str, ast.ClassDef]:
    (cls,) = [
        n for n in tree.body if isinstance(n, ast.ClassDef) and n.name == model
    ]
    return {n.name: n for n in cls.body if isinstance(n, ast.ClassDef)}


def field_names(cls: ast.ClassDef) -> list[str]:
    return [
        n.target.id
        for n in cls.body
        if isinstance(n, ast.AnnAssign) and isinstance(n.target, ast.Name)
    ]


def test_a_stub_is_written_for_the_module_with_models(project: Path):
    write(project, "fakeapp/models.py", MODELS)

    exit_code, output = make_stubs()
    assert exit_code == 0, output
    assert "wrote fakeapp/models.pyi" in output

    text = (project / "fakeapp/models.pyi").read_text()
    assert text.startswith("# Generated by `pangloss make-stubs`")
    tree = ast.parse(text)

    # What the module declares is still there, without bodies
    names = {n.name for n in tree.body if isinstance(n, ast.ClassDef)}
    assert {"Colour", "Place", "Person", "Statement"} <= names
    assert "return self.label" not in text

    # The classes made for a model are nested classes, with the fields
    person = nested(tree, "Person")
    assert {"Create", "Update", "HeadView", "EditView", "ReferenceView"} <= set(person)
    assert "CreateDB" not in person
    assert {"label", "born_in", "colour"} <= set(field_names(person["Create"]))
    # (what a class has from a base class is not written again)
    assert "about_reverse" in field_names(person["HeadView"])
    assert "Person.View" in ast.unparse(person["HeadView"].bases[1])
    assert "label" not in field_names(person["HeadView"])
    assert "Place.ReferenceSet" in ast.unparse(person["Create"])
    assert "Colour" in ast.unparse(person["Create"])

    # A document has no edit view
    assert "EditView" not in nested(tree, "Statement")


def test_a_stub_that_was_not_made_by_the_command_is_not_written_over(project: Path):
    write(project, "fakeapp/models.py", MODELS)
    stub = project / "fakeapp/models.pyi"
    stub.write_text("# mine\n")

    exit_code, output = make_stubs()
    assert exit_code == 0, output
    assert "skipped fakeapp/models.pyi" in output
    assert stub.read_text() == "# mine\n"

    exit_code, output = make_stubs("--force")
    assert exit_code == 0, output
    assert stub.read_text().startswith("# Generated by")


def test_the_stub_is_made_again(project: Path):
    write(project, "fakeapp/models.py", MODELS)
    assert make_stubs()[0] == 0
    first = (project / "fakeapp/models.pyi").read_text()
    # (the registry is of one process; run again as another command would)
    ModelRegistry._reset()
    import sys

    del sys.modules["fakeapp.models"]
    assert make_stubs()[0] == 0
    assert (project / "fakeapp/models.pyi").read_text() == first


def test_models_in_another_module_of_the_project_have_a_stub_too(project: Path):
    write(project, "fakeapp/people.py", MODELS)
    write(project, "fakeapp/models.py", "from fakeapp.people import *\n")

    exit_code, output = make_stubs()
    assert exit_code == 0, output
    assert "wrote fakeapp/people.pyi" in output
    assert "fakeapp/models.pyi" not in output
    assert "Create" in nested(ast.parse((project / "fakeapp/people.pyi").read_text()), "Person")


def test_no_models(project: Path):
    exit_code, output = make_stubs()
    assert exit_code == 0, output
    assert "No models found" in output
    assert not (project / "fakeapp/models.pyi").exists()


def test_it_needs_a_project(tmp_path: Path, monkeypatch):
    monkeypatch.chdir(tmp_path)
    exit_code, output = make_stubs()
    assert exit_code == 1
    assert "No settings found" in output
