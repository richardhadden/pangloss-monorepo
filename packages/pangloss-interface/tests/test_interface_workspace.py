import json
from pathlib import Path

from pangloss_interface import workspace
from pangloss_interface.typescript import models_module

EXPORTED = {"models": {"Person": {"name": "Person"}, "Place": {"name": "Place"}}, "enums": {}}


def make_source(root: Path, files: dict[str, str]) -> Path:
    for name, content in files.items():
        path = root / name
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(content)
    return root


def test_the_module_has_the_definitions_and_the_names():
    text = models_module(EXPORTED)
    assert text.startswith("// Generated by `pangloss interface`")
    assert 'export type ModelName = "Person" | "Place";' in text
    body = text.split("export const definitions: ModelDefinitions = ")[1].rstrip(";\n")
    assert json.loads(body) == EXPORTED
    assert "export type ModelName = never;" in models_module({"models": {}, "enums": {}})


def test_what_npm_makes_is_not_copied(tmp_path):
    source = make_source(
        tmp_path / "source",
        {
            "package.json": "{}",
            "app/src/a.ts": "a",
            "app/node_modules/x/index.js": "x",
            "app/dist/server.js": "built",
            ".env": "SECRET=1",
            "interface-app/src/generated/models.ts": "the package empty one",
        },
    )
    assert workspace.package_files(source) == ["app/src/a.ts", "package.json"]


def test_files_the_package_no_longer_has_are_removed(tmp_path):
    source = make_source(tmp_path / "source", {"a.ts": "1", "b.ts": "2"})
    destination = tmp_path / "destination"
    destination.mkdir()

    written, removed = workspace.sync_sources(destination, source)
    assert sorted(written) == ["a.ts", "b.ts"]
    assert removed == []

    # (the project's own files are left alone, as are those that are the same)
    (destination / "mine.ts").write_text("mine")
    (source / "b.ts").unlink()
    (source / "a.ts").write_text("changed")
    written, removed = workspace.sync_sources(destination, source)
    assert written == ["a.ts"]
    assert removed == ["b.ts"]
    assert not (destination / "b.ts").exists()
    assert (destination / "mine.ts").read_text() == "mine"


def test_prepare_writes_the_models_only_when_they_change(tmp_path):
    first = workspace.prepare(tmp_path, EXPORTED)
    assert first.directory == tmp_path / ".pangloss" / "interface"
    assert workspace.MODELS_MODULE_PATH in first.written

    second = workspace.prepare(tmp_path, EXPORTED)
    assert second.written == []

    changed = {"models": {"Book": {"name": "Book"}}, "enums": {}}
    third = workspace.prepare(tmp_path, changed)
    assert third.written == [workspace.MODELS_MODULE_PATH]
    assert '"Book"' in (first.directory / workspace.MODELS_MODULE_PATH).read_text()
